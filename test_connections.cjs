const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('connections.js','utf8');
const names=['function base64url(','function rawMail(','function eventPayload(','function reportFor(','const localIndia=','const dateIndia='];
const selected=source.split('\n').filter(line=>names.some(name=>line.startsWith(name))).join('\n');
const context=vm.createContext({TextEncoder,TextDecoder,btoa,atob,Intl,Date});
vm.runInContext(selected+'\nglobalThis.testAPI={rawMail,eventPayload,reportFor,localIndia,dateIndia}',context);
const api=context.testAPI;
const raw=api.rawMail({to:'test@example.com',subject:'हिन्दी test',body:'Hello\nनमस्ते',reply:{messageId:'<original@example.com>',references:'<first@example.com>'}});
const mime=Buffer.from(raw,'base64url').toString('utf8');
assert.match(mime,/To: test@example.com/);
assert.match(mime,/In-Reply-To: <original@example.com>/);
const [headers,body]=mime.split('\r\n\r\n');
assert.equal(Buffer.from(body.replace(/\s/g,''),'base64').toString('utf8'),'Hello\nनमस्ते');
const subject=headers.match(/Subject: =\?UTF-8\?B\?(.+)\?=/)[1];
assert.equal(Buffer.from(subject,'base64').toString('utf8'),'हिन्दी test');
assert.throws(()=>api.rawMail({to:'a@example.com\r\nBcc: evil@example.com',subject:'Test',body:'text'}));
assert.equal(api.dateIndia('2026-10-24T20:00:00Z'),'2026-10-25');
assert.equal(api.localIndia('2026-10-24T20:00:00Z'),'2026-10-25T01:30');
assert.equal(api.eventPayload({start:'s',end:'e',reminder:0}).reminders.overrides[0].minutes,0);
assert.equal(api.eventPayload({start:'s',end:'e',reminder:null}).reminders.overrides.length,0);
assert.equal(api.reportFor('One. Two. Three. Four.'),'One. Two. Three.');
console.log('Passed: Unicode mail round-trip, reply headers, header injection rejection, IST date boundaries, reminder payloads, extractive report.');
