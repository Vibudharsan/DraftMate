"""Build inputs for the Android app: launcher icons, the bundled CA certificate and the default server addresses."""
from pathlib import Path
import sys
HERE=Path(__file__).resolve().parent
WEB=HERE.parent
sys.path.insert(0,str(WEB))
from lan import lan_ips,ensure_ca,CA_CERT
from PIL import Image

build=HERE/'build'
# Launcher icons from the web app icon.
source=Image.open(WEB/'icon-512.png')
for folder,size in [('mdpi',48),('hdpi',72),('xhdpi',96),('xxhdpi',144),('xxxhdpi',192)]:
 out=HERE/'res'/f'mipmap-{folder}';out.mkdir(parents=True,exist_ok=True)
 source.resize((size,size),Image.LANCZOS).save(out/'ic_launcher.png',optimize=True)
# The app trusts only this CA (public certificate; the private key never leaves the computer).
ensure_ca()
assets=build/'assets';assets.mkdir(parents=True,exist_ok=True)
(assets/'draftmate_ca.pem').write_bytes(CA_CERT.read_bytes())
# Addresses the app tries first; it asks for one if none respond. The hotspot address (192.168.137.1) is stable.
hosts=[f'https://{ip}:4175' for ip in lan_ips()]
if 'https://192.168.137.1:4175' not in hosts:hosts.append('https://192.168.137.1:4175')
gen=build/'gen'/'com'/'draftmate'/'app';gen.mkdir(parents=True,exist_ok=True)
(gen/'Defaults.java').write_text('package com.draftmate.app;\n\n/** Generated by prepare.py. */\nfinal class Defaults {\n    static final String[] HOSTS = {'+', '.join(f'"{h}"' for h in hosts)+'};\n}\n',encoding='utf-8')
print('Default servers:',', '.join(hosts))
